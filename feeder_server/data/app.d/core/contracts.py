# core/contracts.py
from __future__ import annotations
from dataclasses import dataclass
from typing import Any, Dict, List, Optional, Protocol, Tuple, runtime_checkable, Iterator, Set

# ---- domain ---------------------------------------------------------------

@dataclass(frozen=True, slots=True)
class Tick:
    provider: str          # "binance" | "tradingview" | ...
    stream: str            # "trades" | "quotes" | "ohlcv_1m" | ...
    symbol: str
    ts_ns: int             # unix ns
    seq: Optional[int]     # provider sequence id if available
    payload: Dict[str, Any]
    is_final: bool = True  # provisional vs authoritative

@dataclass(frozen=True, slots=True)
class Envelope:
    batch_id: int
    produced_at_ns: int
    first_offset: Optional[int]
    last_offset: Optional[int]
    rows: List[Tick]

def natural_key(t: Tick) -> Tuple:
    # Use seq if present, otherwise timestamp
    return t.provider, t.stream, t.symbol, t.seq if t.seq is not None else t.ts_ns

# ---- purpose-first interfaces --------------------------------------------

class EventBus(Protocol):
    def publish(self, rows: List[Tick]) -> int: ...
    def drain_for_dh(self, max_n: int, timeout: float) -> List[Envelope]: ...
    def drain_for_journal(self, max_n: int, timeout: float) -> List[Envelope]: ...
    def ack_dh(self, last_batch_id: int) -> None: ...
    def ack_journal(self, last_batch_id: int) -> None: ...

class EventStore(Protocol):
    def append(self, env: Envelope) -> int: ...
    def next_from(self, next_batch_id: int, max_n: int) -> List[Envelope]: ...
    def last_committed(self) -> int: ...
    def mark_committed(self, batch_id: int) -> None: ...

class JournalStore(Protocol):
    def append_batch(self, ticks: List[Tick]) -> int: ...
    def append_envelope(self, env: Envelope) -> int: ...
    def load_recent(self, since_ts_ns: int, columns: Optional[List[str]] = None) -> List[Tick]: ...
    def get_watermark(self, scope: str = "global") -> int: ...
    def set_watermark(self, value: int, scope: str = "global") -> None: ...
    def stream_ticks_since(self, since_ts_ns: int, *, provider_filter: Optional[Set[str]] = None, stream_filter: Optional[Set[str]] = None, page_rows: int = 20_000) -> Iterator[List[Tick]]: ...
    def next_committed_from(self, start_batch_inclusive: int, limit: int) -> list[Envelope]: ...

class DhSink(Protocol):
    def write_envelope(self, env: Envelope) -> None: ...

@runtime_checkable
class Producer(Protocol):
    """Minimal contract Orchestrator needs from any feeder/producer."""
    name: str

    def start(self) -> None: ...
    def stop(self) -> None: ...
    def is_alive(self) -> bool: ...
    def join(self, timeout: Optional[float] = None) -> None: ...