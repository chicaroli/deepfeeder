# runtime/gaps.py
from typing import Protocol

class BackfillClient(Protocol):
    provider: str
    def backfill_trades_from_id(self, symbol: str, from_id: int) -> int: ...
    def backfill_bars_range(self, symbol: str, t0_ns: int, t1_ns: int, overlap: int = 2) -> int: ...

class GapMonitor(Protocol):
    provider: str
    def start(self): ...
    def stop(self): ...
